export const CATALOGUE_BY_ID: Record<string, DeviceSpec> = Object.fromEntries(
  DEVICE_CATALOGUE.map((spec) => [spec.id, spec]),
);

export function specOf(specId: string): DeviceSpec | undefined {
  return CATALOGUE_BY_ID[specId];
}

